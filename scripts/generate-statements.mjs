import { readFileSync, writeFileSync } from "node:fs";
import { recipes } from "../src/services/billing/recipes.ts";
import { buildStatement } from "../src/services/billing/statement-generator.ts";

/**
 * Builds each FinchNode demo patient's itemized statement from that patient's REAL records and writes
 * src/services/scenario-statements.generated.ts. Every charge is backed by a record that FinchNode
 * returned for the service date, except the one deliberately unsupported charge per recipe.
 *
 * Usage:
 *   node scripts/generate-statements.mjs            live pull from the keyless public demo API, then write the file
 *   node scripts/generate-statements.mjs --check    live pull; exit 1 if the checked-in file is out of date (writes nothing)
 *   node scripts/generate-statements.mjs --offline  use the saved fixtures in src/services/medical/fixtures/ instead of the network
 *
 * Only read-only GETs to https://api.finchnode.com/demo/v1 are made. No key is needed.
 */
const offline = process.argv.includes("--offline");
const check = process.argv.includes("--check");
const base = "https://api.finchnode.com/demo/v1";
const target = new URL("../src/services/scenario-statements.generated.ts", import.meta.url);

async function load(subject) {
  if (offline) return JSON.parse(readFileSync(new URL(`../src/services/medical/fixtures/${subject}.json`, import.meta.url), "utf8"));
  const response = await fetch(`${base}/users/${encodeURIComponent(subject)}/records`, { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`FinchNode demo API returned ${response.status} for ${subject}`);
  return response.json();
}

const built = {};
for (const recipe of recipes) {
  const result = buildStatement(recipe, await load(recipe.subject));
  built[recipe.scenarioId] = result;
  console.log(`${recipe.scenarioId}: ${recipe.subject} · ${result.encounter.type} on ${result.serviceDate} · ${result.lines.length} charges · $${result.total.toFixed(2)} (${offline ? "saved copy" : "live pull"})`);
  for (const line of result.lines) console.log(`  ${line.code.padEnd(6)} ${line.description.padEnd(52)} $${line.amount.toFixed(2).padStart(8)}  ${line.unsupported ? "NO RECORD (flagged)" : line.evidence.map((e) => `${e.category}:${e.name}`).join("; ").slice(0, 90)}`);
}

const body = `// GENERATED by scripts/generate-statements.mjs from FinchNode public demo records. Do not edit by hand.
// Re-run \`node scripts/generate-statements.mjs\` (or --check) after changing src/services/billing/recipes.ts.
export interface GeneratedStatement {
  subject: string;
  serviceDate: string;
  encounter: { id: string; type: string };
  invoice: string;
  total: number;
  statement: string;
  lines: Array<{ description: string; code: string; amount: number; unsupported: boolean; evidence: Array<{ id: string; category: string; name: string }> }>;
}

export const generatedStatements: Record<string, GeneratedStatement> = ${JSON.stringify(Object.fromEntries(Object.entries(built).map(([id, { scenarioId: _scenarioId, ...rest }]) => [id, rest])), null, 2)};
`;
if (check) {
  const current = readFileSync(target, "utf8");
  if (current !== body) { console.error("\nscenario-statements.generated.ts is out of date with the FinchNode records"); process.exit(1); }
  console.log("\nchecked-in statements match the records");
} else {
  writeFileSync(target, body);
  console.log(`\nwrote ${target.pathname.replace(process.cwd() + "/", "")}`);
}
